_UNITS = {"г": "g", "гр": "g", "кг": "g", "мл": "ml", "л": "ml", "шт": "pcs"}
_MULT = {"кг": 1000, "л": 1000}
# «6х0,5л», «6 x 500 мл», «900г», «1,5 л», «10 шт»
_PACK_RE = re.compile(r"(?:(\d+)\s*[xх×*]\s*)?(\d+(?:[.,]\d+)?)\s*(кг|гр|г|мл|л|шт)\b", re.IGNORECASE)


def parse_pack(name: str) -> tuple[float | None, str | None]:
    """Упаковка з назви: (кількість у г / мл / шт, одиниця). Береться останній збіг — він зазвичай про вагу."""
    matches = list(_PACK_RE.finditer(name or ""))
    if not matches:
        return None, None
    m = matches[-1]
    count = int(m.group(1)) if m.group(1) else 1
    qty = float(m.group(2).replace(",", "."))
    unit = m.group(3).lower()
    qty *= _MULT.get(unit, 1) * count
    return qty, _UNITS[unit]


def infer_tags(text: str) -> set[str]:
    t = f" {(text or '').lower()} ".replace("’", "'").replace("ʼ", "'")
    tags = set()
    for tag, roots, exceptions in TAG_RULES:
        if any(r in t for r in roots) and not any(e in t for e in exceptions):
            tags.add(tag)
    return tags


def enrich(offer: Offer) -> Offer:
    """Доповнює упаковку і теги, якщо джерело їх не дало."""
    if offer.pack_qty is None and not offer.weighted:
        offer.pack_qty, offer.pack_unit = parse_pack(offer.name)
    offer.tags |= infer_tags(f"{offer.name} {offer.category or ''}")
    return offer


def product_kind(name: str) -> str:
    """Груба «сутність» товару для різноманітності списку: перше значуще слово назви."""
    for w in re.split(r"[\s,«»\"'()]+", (name or "").lower()):
        if len(w) >= 3 and not w[0].isdigit():
            return w[:6]
    return (name or "").lower()[:6]
